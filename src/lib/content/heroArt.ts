function decode(rows: string[]): number[] {
  return [...rows.join('')].map(c => (c === '.' ? -1 : Number.parseInt(c, 36)))
}

export interface HeroDrawing {
  gridW: number
  gridH: number
  palette: string[]
  grid: number[]
}

